"""Gen 2 OU Gymnasium environment with realistic or oracle observations and a capped shaping reward.

Generated by Claude Code.
"""

import os
from dataclasses import dataclass

import numpy as np
from gymnasium.spaces import Box
from poke_env.battle import AbstractBattle
from poke_env.environment import SingleAgentWrapper, SinglesEnv
from poke_env.player import MaxBasePowerPlayer, Player, RandomPlayer, SimpleHeuristicsPlayer
from poke_env.ps_client import LocalhostServerConfiguration, ServerConfiguration

from src.encoding import OBS_SIZE, embed
from src.teams import RandomTeamPool, load_teams

BATTLE_FORMAT = "gen2ou"
MAX_TURNS = 200  # Rest and Leftovers stalling can otherwise run to Showdown's 1000-turn tie
OBSERVATION_MODES = ("realistic", "oracle")
# local Showdown server; cluster jobs each run their own server on a separate port
SHOWDOWN_PORT = int(os.environ.get("SHOWDOWN_PORT", 8000))
SERVER = ServerConfiguration(
    f"ws://localhost:{SHOWDOWN_PORT}/showdown/websocket", LocalhostServerConfiguration.authentication_url
)
OPPONENTS = {
    "random": RandomPlayer,
    "max_power": MaxBasePowerPlayer,
    "heuristic": SimpleHeuristicsPlayer,
}


@dataclass
class RewardConfig:
    win: float = 1.0
    hp_weight: float = 0.1  # shaping total is capped at hp_weight + faint_weight
    faint_weight: float = 0.1


class Gen2Env(SinglesEnv):
    """Two-player gen2ou env; the observation mode decides whether the opponent's team is hidden."""

    def __init__(self, observation_mode: str, teams: list[str], reward: RewardConfig, seed: int | None = None, **kwargs):
        if observation_mode not in OBSERVATION_MODES:
            raise ValueError(f"unknown observation mode {observation_mode!r}")
        super().__init__(
            battle_format=BATTLE_FORMAT,
            team=RandomTeamPool(teams, seed),
            server_configuration=SERVER,
            choose_on_teampreview=False,
            strict=False,  # on a mask edge case, play a random legal move instead of crashing a long run
            **kwargs,
        )
        self.observation_mode = observation_mode
        self.reward = reward
        self.observation_spaces = {
            agent: Box(low=-2.0, high=2.0, shape=(OBS_SIZE,), dtype=np.float32) for agent in self.possible_agents
        }

    def embed_battle(self, battle: AbstractBattle) -> np.ndarray:
        truth = None
        if self.observation_mode == "oracle":
            # the opponent's own battle object holds its full team
            is_agent1 = battle.player_username == self.agent1.username
            truth = self.battle2 if is_agent1 else self.battle1
        return embed(battle, truth)

    def shaping_potential(self, battle: AbstractBattle) -> float:
        """HP and faint difference, each scaled to [-1, 1]; unseen opponents count as full HP."""
        unseen = 6 - len(battle.opponent_team)
        own_hp = sum(mon.current_hp_fraction for mon in battle.team.values())
        opp_hp = sum(mon.current_hp_fraction for mon in battle.opponent_team.values()) + unseen
        own_fainted = sum(mon.fainted for mon in battle.team.values())
        opp_fainted = sum(mon.fainted for mon in battle.opponent_team.values())
        return (
            self.reward.hp_weight * (own_hp - opp_hp) / 6
            + self.reward.faint_weight * (opp_fainted - own_fainted) / 6
        )

    def calc_term_trunc(self, battle: AbstractBattle) -> tuple[bool, bool]:
        """Truncate at the turn cap; the next reset forfeits the unfinished battle."""
        if not battle.finished and battle.turn >= MAX_TURNS:
            return False, True
        return SinglesEnv.calc_term_trunc(battle)

    def calc_reward(self, battle: AbstractBattle) -> float:
        # reward the change in potential, so shaping over a battle telescopes to its final value
        potential = self.shaping_potential(battle)
        reward = potential - self._reward_buffer.get(battle, 0.0)
        self._reward_buffer[battle] = potential
        if battle.won:
            reward += self.reward.win
        elif battle.lost:
            reward -= self.reward.win
        return reward


def make_opponent(name: str) -> Player:
    """A scripted opponent; it never connects, the env plays its moves."""
    return OPPONENTS[name](battle_format=BATTLE_FORMAT, start_listening=False)


def make_env(
    observation_mode: str = "realistic",
    opponent: str = "random",
    split: str = "train",
    reward: RewardConfig | None = None,
    seed: int | None = None,
) -> SingleAgentWrapper:
    """Single-agent env against a scripted opponent, both sides drawing teams from one split."""
    env = Gen2Env(observation_mode, load_teams(split), reward or RewardConfig(), seed)
    return SingleAgentWrapper(env, make_opponent(opponent))


class Curriculum:
    """Ordered opponents; moves to the next one once the validation win rate reaches a threshold."""

    def __init__(self, opponents: list[str], advance_at: float):
        self.opponents = opponents
        self.advance_at = advance_at
        self.stage = 0

    @property
    def opponent(self) -> str:
        return self.opponents[self.stage]

    def update(self, win_rate: float, *envs: SingleAgentWrapper) -> bool:
        """Advance after a good evaluation and swap the opponent in each env; returns True if it advanced."""
        if win_rate < self.advance_at or self.stage == len(self.opponents) - 1:
            return False
        self.stage += 1
        for env in envs:
            env.opponent = make_opponent(self.opponent)
        return True
