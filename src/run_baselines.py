"""Experiment 1: win rates among the scripted players, to calibrate opponent strength.

Usage: python -m src.run_baselines --split val --pool ladder --battles 500

Generated by Claude Code.
"""

import argparse
import csv
from itertools import combinations

from src.env import OPPONENTS
from src.evaluate import scripted_matchup
from src.run_log import RESULTS_DIR
from src.teams import POOLS


def main():
    """Play every pair of scripted players on one team split and write the win rates to data/results/."""
    parser = argparse.ArgumentParser()
    parser.add_argument("--split", default="val", choices=["train", "val", "test"])
    parser.add_argument("--pool", choices=list(POOLS), help="only the split's ladder or expert teams (default: all)")
    parser.add_argument("--battles", type=int, default=500)
    args = parser.parse_args()

    rows = []
    for player, opponent in combinations(OPPONENTS, 2):
        result = scripted_matchup(player, opponent, args.split, args.battles, pool=args.pool)
        rows.append({"player": player, "opponent": opponent, "split": args.split, "pool": args.pool or "all"} | result)
        print(f"{player:>10} vs {opponent:<10} {result['win_rate']:.3f} [{result['ci_low']:.3f}, {result['ci_high']:.3f}]")

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    path = RESULTS_DIR / f"baselines_{args.split}{'_' + args.pool if args.pool else ''}.csv"
    with open(path, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=rows[0].keys())
        writer.writeheader()
        writer.writerows(rows)
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
