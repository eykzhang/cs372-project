"""Command line, periodic validation, checkpoint selection and early stopping shared by the DQN and PPO training scripts.

Generated by Claude Code.
"""

import argparse
import time
from dataclasses import asdict, dataclass

import torch

from src.env import OBSERVATION_MODES, OPPONENTS, Curriculum, RewardConfig, make_env
from src.evaluate import Policy, evaluate_policy
from src.run_log import CsvLog, make_run_dir, override_config

EVAL_FIELDS = ["step", "episodes", "opponent", "win_rate", "ci_low", "ci_high", "mean_turns", "mean_margin"]
SELECT_OPPONENT = "heuristic"  # every run's best.pt is picked against the strongest opponent
VAL_POOL = "ladder"  # validation teams used during training: the held-out ladder pool, not the four expert teams


@dataclass
class EvalSettings:
    eval_every: int = 10_000  # curriculum gate: validation against the current opponent
    eval_battles: int = 100
    select_every: int = 25_000  # checkpoint selection: validation against SELECT_OPPONENT
    select_battles: int = 200
    patience: int = 0  # stop after this many steps on the final stage without a new best; 0 never stops


def parse_training_args(config_class) -> tuple[argparse.Namespace, object, RewardConfig, Curriculum, EvalSettings]:
    """Parse the training command line into arguments, agent config, reward config, curriculum and eval settings."""
    defaults = EvalSettings()
    parser = argparse.ArgumentParser()
    parser.add_argument("--run", required=True, help="run name, used as the folder under models/")
    parser.add_argument("--obs", default="realistic", choices=OBSERVATION_MODES)
    parser.add_argument("--opponents", default="heuristic", help="comma-separated curriculum, weakest first")
    parser.add_argument("--advance-at", type=float, default=0.6, help="validation win rate that moves to the next opponent")
    parser.add_argument("--mixed", action="store_true", help="after an advance, also train against earlier opponents")
    parser.add_argument("--steps", type=int, default=config_class.total_steps)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--eval-every", type=int, default=defaults.eval_every)
    parser.add_argument("--eval-battles", type=int, default=defaults.eval_battles)
    parser.add_argument("--select-every", type=int, default=defaults.select_every)
    parser.add_argument("--select-battles", type=int, default=defaults.select_battles)
    parser.add_argument("--patience", type=int, default=defaults.patience, help="early stopping on the final curriculum stage; 0 is off")
    parser.add_argument("--config", nargs="*", default=[], metavar="KEY=VALUE", help=f"override {config_class.__name__} fields, e.g. lr=3e-4")
    parser.add_argument("--reward", nargs="*", default=[], metavar="KEY=VALUE", help="override RewardConfig fields, e.g. hp_weight=0.5")
    args = parser.parse_args()

    try:
        config = override_config(config_class(total_steps=args.steps), args.config)
        reward_config = override_config(RewardConfig(), args.reward)
    except ValueError as error:
        parser.error(str(error))
    opponents = args.opponents.split(",")
    if any(name not in OPPONENTS for name in opponents):
        parser.error(f"opponents must be from {list(OPPONENTS)}")
    reward_config.gamma = config.gamma  # shaping must use the agent's own discount
    curriculum = Curriculum(opponents, args.advance_at, args.mixed, args.seed)
    eval_settings = EvalSettings(args.eval_every, args.eval_battles, args.select_every, args.select_battles, args.patience)
    return args, config, reward_config, curriculum, eval_settings


class TrainingRun:
    """A run's folder and logs, the curriculum gate, best-checkpoint selection and early stopping."""

    def __init__(
        self, run_name: str, algorithm: str, config, reward_config: RewardConfig, obs_mode: str,
        curriculum: Curriculum, seed: int, eval_settings: EvalSettings, episode_fields: list[str],
    ):
        self.dir = make_run_dir(
            run_name, config, algorithm=algorithm, obs_mode=obs_mode,
            opponents=curriculum.opponents, advance_at=curriculum.advance_at, mixed=curriculum.mixed,
            reward=asdict(reward_config), eval=asdict(eval_settings), val_pool=VAL_POOL, seed=seed,
        )
        self.episode_log = CsvLog(self.dir / "episodes.csv", episode_fields)
        self.eval_log = CsvLog(self.dir / "evals.csv", EVAL_FIELDS)
        self.select_log = CsvLog(self.dir / "selection.csv", EVAL_FIELDS + ["best"])
        self.eval_env = make_env(obs_mode, curriculum.opponent, "val", seed=seed + 1, pool=VAL_POOL)
        self.select_env = make_env(obs_mode, SELECT_OPPONENT, "val", seed=seed + 2, pool=VAL_POOL)
        self.curriculum = curriculum
        self.settings = eval_settings
        self.best_win_rate, self.best_step = -1.0, 0
        self.final_stage_from = 0 if self.on_final_stage() else None
        self.start = time.time()

    def on_final_stage(self) -> bool:
        return self.curriculum.stage == len(self.curriculum.opponents) - 1

    def periodic(self, step: int, episodes: int, policy: Policy, net: torch.nn.Module, train_env) -> tuple[bool, bool]:
        """Run whichever evaluations are due at this step; returns (curriculum advanced, stop training)."""
        advanced = step % self.settings.eval_every == 0 and self.gate(step, episodes, policy, train_env)
        if step % self.settings.select_every == 0:
            self.select(step, episodes, policy, net)
            return advanced, self.out_of_patience(step)
        return advanced, False

    def gate(self, step: int, episodes: int, policy: Policy, train_env) -> bool:
        """Evaluate against the current opponent and advance the curriculum if the win rate is high enough."""
        result = evaluate_policy(self.eval_env, policy, self.settings.eval_battles)
        self.eval_log.write(self.row(step, episodes, self.curriculum.opponent, result))
        print(
            f"step {step:>7}  episodes {episodes:>5}  vs {self.curriculum.opponent:<9} {result['win_rate']:.3f}  "
            f"best vs {SELECT_OPPONENT} {self.best_win_rate:.3f}  {step / (time.time() - self.start):.0f} steps/s",
            flush=True,
        )
        advanced = self.curriculum.update(result["win_rate"], train_env, self.eval_env)
        if advanced:
            print(f"advancing to opponent {self.curriculum.opponent}", flush=True)
            if self.on_final_stage():
                self.final_stage_from = step
        return advanced

    def select(self, step: int, episodes: int, policy: Policy, net: torch.nn.Module):
        """Evaluate against SELECT_OPPONENT and save best.pt on a new best."""
        result = evaluate_policy(self.select_env, policy, self.settings.select_battles)
        is_best = result["win_rate"] > self.best_win_rate
        if is_best:
            self.best_win_rate, self.best_step = result["win_rate"], step
            torch.save(net.state_dict(), self.dir / "best.pt")
        self.select_log.write(self.row(step, episodes, SELECT_OPPONENT, result) | {"best": int(is_best)})

    def out_of_patience(self, step: int) -> bool:
        """True once the final stage has gone `patience` steps without a new best."""
        if not self.settings.patience or self.final_stage_from is None:
            return False
        waited = step - max(self.best_step, self.final_stage_from)
        if waited < self.settings.patience:
            return False
        print(f"stopping at step {step}: no new best since step {self.best_step}", flush=True)
        return True

    @staticmethod
    def row(step: int, episodes: int, opponent: str, result: dict) -> dict:
        return {"step": step, "episodes": episodes, "opponent": opponent} | {field: result[field] for field in EVAL_FIELDS[3:]}

    def finish(self, net: torch.nn.Module):
        """Save final.pt and close the validation envs."""
        torch.save(net.state_dict(), self.dir / "final.pt")
        self.eval_env.close()
        self.select_env.close()
