import argparse
import time
from dataclasses import asdict

import torch

from src.env import OBSERVATION_MODES, OPPONENTS, Curriculum, RewardConfig, make_env
from src.evaluate import Policy, evaluate_policy
from src.run_log import CsvLog, make_run_dir, override_config

EVAL_FIELDS = ["step", "episodes", "opponent", "win_rate", "ci_low", "ci_high", "mean_turns", "mean_margin"]


def parse_training_args(config_class) -> tuple[argparse.Namespace, object, RewardConfig, Curriculum]:
    """Parse the training command line into arguments, agent config, reward config and curriculum."""
    parser = argparse.ArgumentParser()
    parser.add_argument("--run", required=True, help="run name, used as the folder under models/")
    parser.add_argument("--obs", default="realistic", choices=OBSERVATION_MODES)
    parser.add_argument("--opponents", default="heuristic", help="comma-separated curriculum, weakest first")
    parser.add_argument("--advance-at", type=float, default=0.6, help="validation win rate that moves to the next opponent")
    parser.add_argument("--mixed", action="store_true", help="after an advance, also train against earlier opponents")
    parser.add_argument("--steps", type=int, default=config_class.total_steps)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--eval-every", type=int, default=10_000)
    parser.add_argument("--eval-battles", type=int, default=100)
    parser.add_argument("--config", nargs="*", default=[], metavar="KEY=VALUE", help=f"override {config_class.__name__} fields, e.g. lr=3e-4")
    parser.add_argument("--reward", nargs="*", default=[], metavar="KEY=VALUE", help="override RewardConfig fields, e.g. hp_weight=0.5")
    args = parser.parse_args()

    try:
        config = override_config(config_class(total_steps=args.steps), args.config)
        reward_config = override_config(RewardConfig(), args.reward)
    except ValueError as error:
        parser.error(str(error))
    opponents = args.opponents.split(",")
    if any(name not in OPPONENTS for name in opponents):
        parser.error(f"opponents must be from {list(OPPONENTS)}")
    reward_config.gamma = config.gamma  # shaping must use the agent's own discount
    curriculum = Curriculum(opponents, args.advance_at, args.mixed, args.seed)
    return args, config, reward_config, curriculum


class TrainingRun:
    """A run's folder and logs, plus periodic validation that checkpoints the best policy and advances the curriculum."""

    def __init__(
        self, run_name: str, algorithm: str, config, reward_config: RewardConfig, obs_mode: str,
        curriculum: Curriculum, seed: int, eval_battles: int, episode_fields: list[str],
    ):
        self.dir = make_run_dir(
            run_name, config, algorithm=algorithm, obs_mode=obs_mode,
            opponents=curriculum.opponents, advance_at=curriculum.advance_at, mixed=curriculum.mixed,
            reward=asdict(reward_config), seed=seed,
        )
        self.episode_log = CsvLog(self.dir / "episodes.csv", episode_fields)
        self.eval_log = CsvLog(self.dir / "evals.csv", EVAL_FIELDS)
        self.eval_env = make_env(obs_mode, curriculum.opponent, "val", seed=seed + 1)
        self.curriculum = curriculum
        self.eval_battles = eval_battles
        self.best_win_rate = -1.0
        self.start = time.time()

    def evaluate(self, step: int, episodes: int, policy: Policy, net: torch.nn.Module, train_env) -> bool:
        """Evaluate on validation teams, save best.pt on the final opponent, and return True if the curriculum advanced."""
        result = evaluate_policy(self.eval_env, policy, self.eval_battles)
        self.eval_log.write({"step": step, "episodes": episodes, "opponent": self.curriculum.opponent} | {
            field: result[field] for field in EVAL_FIELDS[3:]
        })
        on_final_stage = self.curriculum.stage == len(self.curriculum.opponents) - 1
        if on_final_stage and result["win_rate"] > self.best_win_rate:
            self.best_win_rate = result["win_rate"]
            torch.save(net.state_dict(), self.dir / "best.pt")
        print(
            f"step {step:>7}  episodes {episodes:>5}  val win {result['win_rate']:.3f}  "
            f"best {self.best_win_rate:.3f}  {step / (time.time() - self.start):.0f} steps/s",
            flush=True,
        )
        advanced = self.curriculum.update(result["win_rate"], train_env, self.eval_env)
        if advanced:
            print(f"advancing to opponent {self.curriculum.opponent}", flush=True)
        return advanced

    def finish(self, net: torch.nn.Module):
        """Save final.pt and close the validation env."""
        torch.save(net.state_dict(), self.dir / "final.pt")
        self.eval_env.close()
