"""Evaluate saved checkpoints of several training runs against scripted opponents under one protocol.

Usage: python -m src.evaluate_runs --runs dqn_sweep_base ppo_sweep_base --split test --pool ladder --out sweep_test

Generated by Claude Code.
"""

import argparse
import csv
import json

from src.env import OPPONENTS, make_env
from src.evaluate import evaluate_policy, load_agent
from src.run_log import MODELS_DIR, RESULTS_DIR
from src.teams import POOLS


def evaluate_run(run: str, checkpoint: str, opponent: str, split: str, pool: str | None, n_battles: int, seed: int) -> dict:
    """Win rate of one run's checkpoint against one scripted opponent, in the run's own observation mode."""
    settings = json.loads((MODELS_DIR / run / "config.json").read_text())
    agent = load_agent(run, checkpoint)
    env = make_env(settings["obs_mode"], opponent, split, seed=seed, pool=pool)
    result = evaluate_policy(env, agent.act, n_battles)
    env.close()
    return {
        "run": run, "algorithm": settings["algorithm"], "obs_mode": settings["obs_mode"], "checkpoint": checkpoint,
        "opponent": opponent, "split": split, "pool": pool or "all",
    } | result


def main():
    """Evaluate each listed run against each opponent and write one CSV to data/results/."""
    parser = argparse.ArgumentParser()
    parser.add_argument("--runs", nargs="+", required=True)
    parser.add_argument("--checkpoint", default="final", choices=["final", "best"])
    parser.add_argument("--opponents", default="max_power,heuristic")
    parser.add_argument("--split", default="val", choices=["train", "val", "test"])
    parser.add_argument("--pool", choices=list(POOLS), help="only the split's ladder or expert teams (default: all)")
    parser.add_argument("--battles", type=int, default=300)
    parser.add_argument("--seed", type=int, default=100)  # differs from the seeds used during training evals
    parser.add_argument("--out", required=True, help="output name, written to data/results/<out>.csv")
    args = parser.parse_args()

    opponents = args.opponents.split(",")
    for name in opponents:
        if name not in OPPONENTS:
            raise ValueError(f"unknown opponent {name!r}")

    rows = []
    for run in args.runs:
        for opponent in opponents:
            row = evaluate_run(run, args.checkpoint, opponent, args.split, args.pool, args.battles, args.seed)
            rows.append(row)
            print(f"{run:<22} vs {opponent:<10} {row['win_rate']:.3f} [{row['ci_low']:.3f}, {row['ci_high']:.3f}]", flush=True)

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    path = RESULTS_DIR / f"{args.out}.csv"
    with open(path, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=rows[0].keys())
        writer.writeheader()
        writer.writerows(rows)
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
