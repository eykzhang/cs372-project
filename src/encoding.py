"""Turn a Gen 2 battle into a fixed-length feature vector.

Two observation modes share one layout. The realistic mode shows only what a
player could know. The oracle mode fills the same slots for the opponent from
their true team (every Pokemon, move and item), so the two differ only in what
is hidden.

Generated by Claude Code.
"""

import math

import numpy as np
from poke_env.battle import (
    AbstractBattle,
    Effect,
    Move,
    MoveCategory,
    Pokemon,
    PokemonType,
    SideCondition,
    Status,
    Weather,
)
from poke_env.data import GenData

TYPE_CHART = GenData.from_gen(2).type_chart

# vocabularies
TYPES = [t for t in PokemonType if t.name in TYPE_CHART]  # the 17 Gen 2 types
STATUSES = [Status.BRN, Status.FRZ, Status.PAR, Status.PSN, Status.SLP, Status.TOX]
BASE_STATS = ["hp", "atk", "def", "spa", "spd", "spe"]
BOOSTS = ["atk", "def", "spa", "spd", "spe", "accuracy", "evasion"]
CATEGORIES = [MoveCategory.PHYSICAL, MoveCategory.SPECIAL, MoveCategory.STATUS]
ITEMS = ["leftovers"]  # Leftovers is on 102 of 108 Pokemon in the team pool
WEATHERS = [Weather.RAINDANCE, Weather.SUNNYDAY, Weather.SANDSTORM]
SIDE_CONDITIONS = [SideCondition.SPIKES, SideCondition.REFLECT, SideCondition.LIGHT_SCREEN, SideCondition.SAFEGUARD]
VOLATILES = [Effect.SUBSTITUTE, Effect.LEECH_SEED, Effect.CONFUSION, Effect.CURSE, Effect.ENCORE]

# Gen 2 OU move roles worth flagging when an opponent reveals them
MOVE_ROLES = {
    "recovery": {"rest", "recover", "milkdrink", "softboiled", "morningsun", "moonlight", "synthesis"},
    "setup": {"curse", "swordsdance", "growth", "bellydrum", "agility"},
    "explosion": {"explosion", "selfdestruct"},
    "sleep": {"lovelykiss", "sleeppowder", "spore", "hypnosis", "sing"},
    "spikes": {"spikes"},
    "phazing": {"roar", "whirlwind"},
    "rapidspin": {"rapidspin"},
    "sleeptalk": {"sleeptalk"},
}

WEATHER_TURNS = 5
IMMUNE = -1.5  # effectiveness feature for a 0x matchup, below the -1 of a 0.25x resist

POKEMON_SIZE = (
    1  # revealed
    + len(TYPES)
    + len(BASE_STATS)
    + 1  # hp fraction
    + len(STATUSES)
    + len(ITEMS) + 3  # known item, other item, no item, unknown item
    + 2  # fainted, active
    + len(TYPES)  # types of known damaging moves
    + len(MOVE_ROLES)
    + 1  # known move count
    + 2  # best attack into the opposing active, worst hit taken from it
)
MOVE_SIZE = 1 + 3 + len(CATEGORIES) + len(TYPES) + 3  # exists, power/acc/pp, category, type, eff/stab/priority
FIELD_SIZE = (
    1  # turn
    + len(WEATHERS) + 1  # weather and turns left
    + 2 * len(SIDE_CONDITIONS)
    + 2 * len(BOOSTS)
    + 2 * len(VOLATILES)
    + 2  # Pokemon left on each side
    + 1  # trapped
)
OBS_SIZE = 12 * POKEMON_SIZE + 4 * MOVE_SIZE + FIELD_SIZE


def one_hot(value, vocabulary) -> list[float]:
    return [1.0 if value == v else 0.0 for v in vocabulary]


def effectiveness(attack_type: PokemonType, defender: Pokemon) -> float:
    """Gen 2 type multiplier on a log scale: 0.25x -> -1, 1x -> 0, 4x -> 1."""
    if attack_type not in TYPES:
        return 0.0
    multiplier = attack_type.damage_multiplier(defender.type_1, defender.type_2, type_chart=TYPE_CHART)
    return math.log2(multiplier) / 2 if multiplier > 0 else IMMUNE


def is_damaging(move: Move) -> bool:
    return move.category != MoveCategory.STATUS


def known_type(move: Move) -> PokemonType | None:
    """A move's type, or None for an opponent's Hidden Power, which poke-env reports as Normal."""
    if move.id.startswith("hiddenpower") and move.type == PokemonType.NORMAL:
        return None  # Gen 2 Hidden Power is never Normal; the protocol does not reveal its type
    return move.type


def encode_item(item: str | None) -> list[float]:
    """One-hot held item, with extra slots for an unlisted item, no item, and an unrevealed item."""
    if item == "unknown_item":
        return [0.0] * (len(ITEMS) + 2) + [1.0]
    if not item:
        return [0.0] * (len(ITEMS) + 1) + [1.0, 0.0]
    if item in ITEMS:
        return one_hot(item, ITEMS) + [0.0, 0.0, 0.0]
    return [0.0] * len(ITEMS) + [1.0, 0.0, 0.0]


def encode_pokemon(mon: Pokemon | None, opposing_active: Pokemon | None) -> list[float]:
    """Features for one team slot; None is an opponent Pokemon not yet revealed."""
    if mon is None:
        # unseen Pokemon have never been hit, so full HP is known, not leaked
        unseen = [0.0] * (1 + len(TYPES) + len(BASE_STATS)) + [1.0] + [0.0] * len(STATUSES) + encode_item("unknown_item")
        return unseen + [0.0] * (POKEMON_SIZE - len(unseen))

    moves = list(mon.moves.values())
    move_types = [1.0 if any(is_damaging(m) and known_type(m) == t for m in moves) else 0.0 for t in TYPES]
    roles = [1.0 if any(m.id in ids for m in moves) else 0.0 for ids in MOVE_ROLES.values()]

    # matchup against whatever is currently in front of this Pokemon
    best_attack, worst_taken = 0.0, 0.0
    if opposing_active is not None:
        attacks = [effectiveness(known_type(m), opposing_active) for m in moves if is_damaging(m) and known_type(m)]
        best_attack = max(attacks, default=0.0)
        worst_taken = max(effectiveness(t, mon) for t in opposing_active.types)

    return (
        [1.0]
        + [1.0 if t in mon.types else 0.0 for t in TYPES]
        + [mon.base_stats[s] / 255 for s in BASE_STATS]
        + [mon.current_hp_fraction]
        + one_hot(mon.status, STATUSES)
        + encode_item(mon.item)
        + [float(mon.fainted), float(bool(mon.active))]
        + move_types
        + roles
        + [len(moves) / 4]
        + [best_attack, worst_taken]
    )


def encode_move(move: Move | None, attacker: Pokemon, defender: Pokemon | None) -> list[float]:
    """Features for one of the active Pokemon's move slots."""
    if move is None:
        return [0.0] * MOVE_SIZE
    eff = effectiveness(move.type, defender) if defender is not None and is_damaging(move) else 0.0
    stab = 1.0 if is_damaging(move) and move.type in attacker.types else 0.0
    return (
        [1.0, move.base_power / 150, float(move.accuracy), move.current_pp / max(move.max_pp, 1)]
        + one_hot(move.category, CATEGORIES)
        + one_hot(move.type, TYPES)
        + [eff, stab, move.priority / 3]  # Gen 2 priorities run from -1 to +3
    )


def encode_side(conditions: dict) -> list[float]:
    return [1.0 if c in conditions else 0.0 for c in SIDE_CONDITIONS]


def encode_active_state(mon: Pokemon | None) -> list[float]:
    """Stat boosts and volatile effects, which only matter while a Pokemon is in."""
    if mon is None:
        return [0.0] * (len(BOOSTS) + len(VOLATILES))
    return [mon.boosts[b] / 6 for b in BOOSTS] + [1.0 if e in mon.effects else 0.0 for e in VOLATILES]


def opponent_slots(battle: AbstractBattle, truth: AbstractBattle | None) -> list[Pokemon | None]:
    """Opponent team in reveal order, padded to 6 with unseen Pokemon (or true ones for the oracle)."""
    revealed = list(battle.opponent_team.values())
    if truth is None:
        return revealed + [None] * (6 - len(revealed))
    true_team = {mon.species: mon for mon in truth.team.values()}
    seen = {mon.species for mon in revealed}
    unseen = [mon for species, mon in true_team.items() if species not in seen]
    return [true_team.get(mon.species, mon) for mon in revealed] + unseen


def embed(battle: AbstractBattle, truth: AbstractBattle | None = None) -> np.ndarray:
    """Encode a battle from one player's view; pass the opponent's own battle as `truth` for the oracle."""
    own_active = battle.active_pokemon
    opp_active = battle.opponent_active_pokemon
    opponents = opponent_slots(battle, truth)

    # own team keeps poke-env's order, so slot i is switch action i
    features: list[float] = []
    for mon in battle.team.values():
        features += encode_pokemon(mon, opp_active)
    for mon in opponents:
        features += encode_pokemon(mon, own_active)

    moves = list(own_active.moves.values())[:4] if own_active is not None else []
    for i in range(4):
        move = moves[i] if i < len(moves) else None
        features += encode_move(move, own_active, opp_active)

    # field
    weather = next(iter(battle.weather), None)
    weather_left = 0.0
    if weather is not None:
        weather_left = max(0, WEATHER_TURNS - (battle.turn - battle.weather[weather])) / WEATHER_TURNS
    own_left = sum(not mon.fainted for mon in battle.team.values())
    opp_left = sum(mon is None or not mon.fainted for mon in opponents)
    features += (
        [min(battle.turn, 100) / 100]
        + one_hot(weather, WEATHERS)
        + [weather_left]
        + encode_side(battle.side_conditions)
        + encode_side(battle.opponent_side_conditions)
        + encode_active_state(own_active)
        + encode_active_state(opp_active)
        + [own_left / 6, opp_left / 6]
        + [float(bool(battle.trapped))]
    )
    return np.array(features, dtype=np.float32)
