import csv
import json
from dataclasses import asdict
from pathlib import Path

MODELS_DIR = Path(__file__).resolve().parent.parent / "models"
RESULTS_DIR = Path(__file__).resolve().parent.parent / "data" / "results"


def override_config(config, overrides: list[str]):
    """Apply key=value overrides from the command line to an agent config dataclass."""
    for item in overrides:
        key, _, value = item.partition("=")
        if not hasattr(config, key):
            raise ValueError(f"{type(config).__name__} has no field {key!r}")
        current = getattr(config, key)
        if isinstance(current, bool):
            value = value.lower() in ("1", "true")
        elif isinstance(current, tuple):
            value = tuple(int(size) for size in value.split(","))
        else:
            value = type(current)(value)
        setattr(config, key, value)
    return config


def make_run_dir(run_name: str, config, **settings) -> Path:
    """Create models/<run_name>/ and save the agent config and run settings in it."""
    run_dir = MODELS_DIR / run_name
    run_dir.mkdir(parents=True, exist_ok=True)
    with open(run_dir / "config.json", "w") as f:
        json.dump({"agent": asdict(config), **settings}, f, indent=2)
    return run_dir


class CsvLog:
    """Append rows to a CSV file, flushing each one so a crashed run keeps its log."""

    def __init__(self, path: Path, fields: list[str]):
        self.file = open(path, "w", newline="")
        self.writer = csv.DictWriter(self.file, fieldnames=fields)
        self.writer.writeheader()

    def write(self, row: dict):
        self.writer.writerow(row)
        self.file.flush()
