"""Train a Double DQN agent through a curriculum of scripted opponents, keeping the best checkpoint against the last one.

Usage: python -m src.train_dqn --run dqn_realistic --obs realistic --opponents random,max_power,heuristic --steps 200000

Generated by Claude Code.
"""

import argparse
import time

import numpy as np
import torch

from src.dqn import DQNAgent, DQNConfig
from src.encoding import OBS_SIZE
from src.env import OBSERVATION_MODES, OPPONENTS, Curriculum, make_env
from src.evaluate import evaluate_policy
from src.run_log import CsvLog, make_run_dir, override_config


def train(config: DQNConfig, run_name: str, obs_mode: str, curriculum: Curriculum, seed: int, eval_every: int, eval_battles: int):
    env = make_env(obs_mode, curriculum.opponent, "train", seed=seed)
    eval_env = make_env(obs_mode, curriculum.opponent, "val", seed=seed + 1)
    agent = DQNAgent(OBS_SIZE, env.action_space.n, config, seed)
    run_dir = make_run_dir(
        run_name, config, algorithm="dqn", obs_mode=obs_mode,
        opponents=curriculum.opponents, advance_at=curriculum.advance_at, seed=seed,
    )
    episode_log = CsvLog(run_dir / "episodes.csv", ["episode", "step", "return", "won", "turns", "epsilon", "loss"])
    eval_log = CsvLog(run_dir / "evals.csv", ["step", "episodes", "opponent", "win_rate", "ci_low", "ci_high", "mean_turns", "mean_margin"])

    obs, _ = env.reset()
    episode, episode_return, losses = 0, 0.0, []
    best_win_rate, start = -1.0, time.time()

    # training loop
    for step in range(1, config.total_steps + 1):
        epsilon = agent.epsilon(step)
        action = agent.act(obs, epsilon)
        next_obs, reward, terminated, truncated, _ = env.step(np.int64(action))
        done = terminated or truncated
        # a turn-cap cutoff is not a real end, so only finished battles stop the bootstrap
        battle_over = env.env.battle1.finished
        agent.replay_buffer.add(
            obs["observation"], action, reward, next_obs["observation"], next_obs["action_mask"].astype(bool), battle_over
        )
        episode_return += reward
        obs = next_obs

        if done:
            episode += 1
            battle = env.env.battle1
            mean_loss = float(np.mean(losses)) if losses else float("nan")
            episode_log.write({
                "episode": episode, "step": step, "return": episode_return, "won": int(bool(battle.won)),
                "turns": battle.turn, "epsilon": epsilon, "loss": mean_loss,
            })
            obs, _ = env.reset()
            episode_return, losses = 0.0, []

        if step >= config.learning_starts and step % config.train_every == 0:
            losses.append(agent.update())
        if step % config.target_update_every == 0:
            agent.sync_target()

        # periodic greedy evaluation on validation teams
        if step % eval_every == 0:
            result = evaluate_policy(eval_env, agent.act, eval_battles)
            eval_log.write({
                "step": step, "episodes": episode, "opponent": curriculum.opponent,
                "win_rate": result["win_rate"], "ci_low": result["ci_low"], "ci_high": result["ci_high"],
                "mean_turns": result["mean_turns"], "mean_margin": result["mean_margin"],
            })
            on_final_stage = curriculum.stage == len(curriculum.opponents) - 1
            if on_final_stage and result["win_rate"] > best_win_rate:
                best_win_rate = result["win_rate"]
                torch.save(agent.q_net.state_dict(), run_dir / "best.pt")
            print(
                f"step {step:>7}  episodes {episode:>5}  eps {epsilon:.2f}  "
                f"val win {result['win_rate']:.3f}  best {best_win_rate:.3f}  {step / (time.time() - start):.0f} steps/s",
                flush=True,
            )
            if curriculum.update(result["win_rate"], env, eval_env):
                print(f"advancing to opponent {curriculum.opponent}", flush=True)

    torch.save(agent.q_net.state_dict(), run_dir / "final.pt")
    env.close()
    eval_env.close()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--run", required=True, help="run name, used as the folder under models/")
    parser.add_argument("--obs", default="realistic", choices=OBSERVATION_MODES)
    parser.add_argument("--opponents", default="heuristic", help="comma-separated curriculum, weakest first")
    parser.add_argument("--advance-at", type=float, default=0.6, help="validation win rate that moves to the next opponent")
    parser.add_argument("--steps", type=int, default=DQNConfig.total_steps)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--eval-every", type=int, default=10_000)
    parser.add_argument("--eval-battles", type=int, default=100)
    parser.add_argument("--config", nargs="*", default=[], metavar="KEY=VALUE", help="override DQNConfig fields, e.g. lr=3e-4")
    args = parser.parse_args()
    try:
        config = override_config(DQNConfig(total_steps=args.steps), args.config)
    except ValueError as error:
        parser.error(str(error))
    torch.set_num_threads(1)  # the network is small; extra threads only compete with the simulator
    opponents = args.opponents.split(",")
    if any(name not in OPPONENTS for name in opponents):
        parser.error(f"opponents must be from {list(OPPONENTS)}")
    train(config, args.run, args.obs, Curriculum(opponents, args.advance_at), args.seed, args.eval_every, args.eval_battles)


if __name__ == "__main__":
    main()
