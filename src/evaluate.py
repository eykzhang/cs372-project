N_ACTIONS = 10

Policy = Callable[[dict], int]  # maps an observation dict (features and action mask) to an action


def wilson_interval(wins: int, n: int, z: float = 1.96) -> tuple[float, float]:
    """95% Wilson score interval for a win rate."""
    if n == 0:
        return 0.0, 1.0
    p = wins / n
    center = (p + z**2 / (2 * n)) / (1 + z**2 / n)
    half = z * math.sqrt(p * (1 - p) / n + z**2 / (4 * n**2)) / (1 + z**2 / n)
    return center - half, center + half


def summarize(wins: int, n: int) -> dict:
    low, high = wilson_interval(wins, n)
    return {"battles": n, "wins": wins, "win_rate": wins / n, "ci_low": low, "ci_high": high}


def evaluate_policy(env: SingleAgentWrapper, policy: Policy, n_battles: int) -> dict:
    """Play n_battles with a fixed policy and report win rate, battle length and margin."""
    wins, turns, margins = 0, [], []
    for _ in range(n_battles):
        obs, _ = env.reset()
        done = False
        while not done:
            obs, _, terminated, truncated, _ = env.step(np.int64(policy(obs)))
            done = terminated or truncated
        battle = env.env.battle1
        wins += int(bool(battle.won))
        turns.append(battle.turn)
        # margin of victory: own Pokemon left minus opponent Pokemon left
        own_left = sum(not mon.fainted for mon in battle.team.values())
        opp_left = 6 - sum(mon.fainted for mon in battle.opponent_team.values())
        margins.append(own_left - opp_left)
    return summarize(wins, n_battles) | {"mean_turns": float(np.mean(turns)), "mean_margin": float(np.mean(margins))}


def scripted_matchup(player: str, opponent: str, split: str, n_battles: int, seed: int = 0) -> dict:
    """Win rate of one scripted player against another, both drawing teams from a split."""
    teams = load_teams(split)
    p1 = OPPONENTS[player](battle_format=BATTLE_FORMAT, team=RandomTeamPool(teams, seed), max_concurrent_battles=10, server_configuration=SERVER)
    p2 = OPPONENTS[opponent](battle_format=BATTLE_FORMAT, team=RandomTeamPool(teams, seed + 1), max_concurrent_battles=10, server_configuration=SERVER)
    asyncio.run(p1.battle_against(p2, n_battles=n_battles))
    return summarize(p1.n_won_battles, p1.n_finished_battles)


def load_agent(run_name: str, checkpoint: str = "best") -> DQNAgent | PPOAgent:
    """Rebuild a trained agent from models/<run_name>/config.json and a saved checkpoint."""
    run_dir = MODELS_DIR / run_name
    settings = json.loads((run_dir / "config.json").read_text())
    agent_config = settings["agent"] | {"hidden_sizes": tuple(settings["agent"]["hidden_sizes"])}
    weights = torch.load(run_dir / f"{checkpoint}.pt")
    if settings["algorithm"] == "dqn":
        agent = DQNAgent(OBS_SIZE, N_ACTIONS, DQNConfig(**agent_config))
        agent.q_net.load_state_dict(weights)
    else:
        agent = PPOAgent(OBS_SIZE, N_ACTIONS, PPOConfig(**agent_config))
        agent.net.load_state_dict(weights)
    return agent
