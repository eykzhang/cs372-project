"""PPO with a shared-trunk actor-critic, GAE and a masked categorical policy.

Generated by Claude Code.
"""

from dataclasses import dataclass

import numpy as np
import torch
import torch.nn as nn
from torch.distributions import Categorical


@dataclass
class PPOConfig:
    total_steps: int = 200_000
    rollout_steps: int = 2_048  # env steps collected per update
    epochs: int = 4
    minibatch_size: int = 256
    lr: float = 3e-4
    gamma: float = 0.99
    gae_lambda: float = 0.95
    clip_range: float = 0.2
    entropy_coef: float = 0.01
    value_coef: float = 0.5
    max_grad_norm: float = 0.5
    hidden_sizes: tuple[int, ...] = (512, 256)


class ActorCritic(nn.Module):
    """Shared MLP trunk with a policy head (action logits) and a value head."""

    def __init__(self, obs_size: int, n_actions: int, hidden_sizes: tuple[int, ...]):
        super().__init__()
        layers, in_size = [], obs_size
        for size in hidden_sizes:
            layers += [nn.Linear(in_size, size), nn.Tanh()]
            in_size = size
        self.trunk = nn.Sequential(*layers)
        self.policy_head = nn.Linear(in_size, n_actions)
        self.value_head = nn.Linear(in_size, 1)
        # small initial logits so the starting policy is close to uniform over legal actions
        nn.init.orthogonal_(self.policy_head.weight, gain=0.01)
        nn.init.zeros_(self.policy_head.bias)

    def forward(self, obs: torch.Tensor, mask: torch.Tensor) -> tuple[Categorical, torch.Tensor]:
        h = self.trunk(obs)
        # illegal actions get -inf logits, so zero probability
        logits = self.policy_head(h).masked_fill(~mask, float("-inf"))
        return Categorical(logits=logits), self.value_head(h).squeeze(-1)


class RolloutBuffer:
    """One rollout of on-policy experience, cleared after every update."""

    def __init__(self, size: int, obs_size: int, n_actions: int):
        self.obs = np.zeros((size, obs_size), dtype=np.float32)
        self.masks = np.zeros((size, n_actions), dtype=bool)
        self.actions = np.zeros(size, dtype=np.int64)
        self.log_probs = np.zeros(size, dtype=np.float32)
        self.values = np.zeros(size, dtype=np.float32)
        self.rewards = np.zeros(size, dtype=np.float32)
        self.dones = np.zeros(size, dtype=bool)
        self.index = 0

    def add(self, obs, mask, action, log_prob, value, reward, done):
        i = self.index
        self.obs[i], self.masks[i], self.actions[i] = obs, mask, action
        self.log_probs[i], self.values[i], self.rewards[i], self.dones[i] = log_prob, value, reward, done
        self.index += 1

    def full(self) -> bool:
        return self.index == len(self.obs)


def compute_gae(rewards, values, dones, last_value: float, gamma: float, lam: float) -> tuple[np.ndarray, np.ndarray]:
    """Generalized advantage estimation over one rollout; returns advantages and value targets."""
    advantages = np.zeros_like(rewards)
    next_value, running = last_value, 0.0
    for t in reversed(range(len(rewards))):
        not_done = 1.0 - dones[t]
        delta = rewards[t] + gamma * next_value * not_done - values[t]
        running = delta + gamma * lam * not_done * running
        advantages[t] = running
        next_value = values[t]
    return advantages, advantages + values


class PPOAgent:
    """Actor-critic trained with the clipped surrogate objective."""

    def __init__(self, obs_size: int, n_actions: int, config: PPOConfig, seed: int = 0):
        torch.manual_seed(seed)
        self.config = config
        self.rng = np.random.default_rng(seed)
        self.net = ActorCritic(obs_size, n_actions, config.hidden_sizes)
        self.optimizer = torch.optim.Adam(self.net.parameters(), lr=config.lr)
        self.buffer = RolloutBuffer(config.rollout_steps, obs_size, n_actions)

    def step(self, obs: dict) -> tuple[int, float, float]:
        """Sample an action; also return its log-probability and the state value."""
        with torch.no_grad():
            dist, value = self.net(*self.to_tensors(obs))
            action = dist.sample()
        return int(action), float(dist.log_prob(action)), float(value)

    def act(self, obs: dict) -> int:
        """The trained stochastic policy, used for evaluation."""
        return self.step(obs)[0]

    def value(self, obs: dict) -> float:
        with torch.no_grad():
            return float(self.net(*self.to_tensors(obs))[1])

    @staticmethod
    def to_tensors(obs: dict) -> tuple[torch.Tensor, torch.Tensor]:
        features = torch.from_numpy(obs["observation"]).unsqueeze(0)
        mask = torch.from_numpy(obs["action_mask"].astype(bool)).unsqueeze(0)
        return features, mask

    def update(self, last_value: float) -> dict[str, float]:
        """Several epochs of minibatch updates on the current rollout, then clear it."""
        cfg, buf = self.config, self.buffer
        advantages, returns = compute_gae(buf.rewards, buf.values, buf.dones, last_value, cfg.gamma, cfg.gae_lambda)

        obs = torch.from_numpy(buf.obs)
        masks = torch.from_numpy(buf.masks)
        actions = torch.from_numpy(buf.actions)
        old_log_probs = torch.from_numpy(buf.log_probs)
        advantages = torch.from_numpy(advantages)
        returns = torch.from_numpy(returns)

        stats = {"policy_loss": [], "value_loss": [], "entropy": [], "clip_fraction": []}
        for _ in range(cfg.epochs):
            for idx in np.array_split(self.rng.permutation(len(obs)), len(obs) // cfg.minibatch_size):
                dist, values = self.net(obs[idx], masks[idx])
                log_probs = dist.log_prob(actions[idx])
                adv = advantages[idx]
                adv = (adv - adv.mean()) / (adv.std() + 1e-8)

                # clipped surrogate objective
                ratio = torch.exp(log_probs - old_log_probs[idx])
                clipped = torch.clamp(ratio, 1 - cfg.clip_range, 1 + cfg.clip_range)
                policy_loss = -torch.min(ratio * adv, clipped * adv).mean()
                value_loss = (returns[idx] - values).pow(2).mean()
                entropy = dist.entropy().mean()
                loss = policy_loss + cfg.value_coef * value_loss - cfg.entropy_coef * entropy

                self.optimizer.zero_grad()
                loss.backward()
                nn.utils.clip_grad_norm_(self.net.parameters(), cfg.max_grad_norm)
                self.optimizer.step()

                stats["policy_loss"].append(policy_loss.item())
                stats["value_loss"].append(value_loss.item())
                stats["entropy"].append(entropy.item())
                stats["clip_fraction"].append(((ratio - 1).abs() > cfg.clip_range).float().mean().item())

        self.buffer.index = 0
        return {k: float(np.mean(v)) for k, v in stats.items()}
