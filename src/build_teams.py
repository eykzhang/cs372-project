"""Rebuild data/teams/ from Metamon's team dataset at a pinned revision.

Usage: python -m src.build_teams [--out data/teams]

Generated by Claude Code.
"""

import argparse
import io
import random
import tarfile
import urllib.request
from pathlib import Path

from poke_env.teambuilder import Teambuilder

from src.teams import SPLITS, TEAMS_DIR

DATASET_URL = "https://huggingface.co/datasets/jakegrigsby/metamon-teams/resolve"
REVISION = "bff785c80a06273faee1c675d368948f5dd65d44"
SPLIT_SIZES = {"train": 11, "val": 4, "test": 3}
SPLIT_SEED = 0


def download_teams(subset: str) -> dict[str, str]:
    """Download one Gen 2 OU archive and return {file name: team text}."""
    url = f"{DATASET_URL}/{REVISION}/{subset}/gen2ou.tar.gz"
    with urllib.request.urlopen(url) as response:
        archive = tarfile.open(fileobj=io.BytesIO(response.read()), mode="r:gz")
    teams = {}
    for member in archive.getmembers():
        if member.isfile() and member.name.endswith(".gen2ou_team"):
            teams[Path(member.name).name] = archive.extractfile(member).read().decode()
    return teams


def team_number(name: str) -> int:
    return int(name.removesuffix(".gen2ou_team").split("_")[-1])


def species_set(team_text: str) -> frozenset[str]:
    """The six Pokemon on a team, ignoring nicknames, moves and items."""
    mons = [mon for mon in Teambuilder.parse_showdown_team(team_text) if mon.moves]
    return frozenset(mon.species or mon.nickname for mon in mons)


def split_competitive(teams: dict[str, str]) -> dict[str, dict[str, str]]:
    """Shuffle the expert teams once with a fixed seed and cut them 11 / 4 / 3."""
    names = sorted(teams, key=team_number)
    random.Random(SPLIT_SEED).shuffle(names)
    splits, start = {}, 0
    for split in SPLITS:
        chunk = names[start:start + SPLIT_SIZES[split]]
        splits[split] = {name: teams[name] for name in chunk}
        start += SPLIT_SIZES[split]
    return splits


def filter_ladder(teams: dict[str, str], held_out: list[str]) -> dict[str, str]:
    """Drop exact duplicates and teams with the same six Pokemon as a validation or test team."""
    held_out_species = {species_set(text) for text in held_out}
    kept, seen = {}, set()
    for name in sorted(teams, key=team_number):
        mons = [mon for mon in Teambuilder.parse_showdown_team(teams[name]) if mon.moves]
        packed = Teambuilder.join_team(mons)
        is_duplicate = packed in seen
        seen.add(packed)
        if is_duplicate or species_set(teams[name]) in held_out_species:
            continue
        kept[name.replace("team_", "ladder_")] = teams[name]
    return kept


def main():
    """Download both team sets, redo the seeded split and ladder filters, and write the team files."""
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, default=TEAMS_DIR)
    args = parser.parse_args()

    splits = split_competitive(download_teams("competitive"))
    held_out = list(splits["val"].values()) + list(splits["test"].values())
    ladder = filter_ladder(download_teams("hl_05_26"), held_out)
    splits["train"] |= ladder

    # replace any existing team files so the output matches the split exactly
    for split, teams in splits.items():
        split_dir = args.out / split
        split_dir.mkdir(parents=True, exist_ok=True)
        for old in split_dir.glob("*.gen2ou_team"):
            old.unlink()
        for name, text in teams.items():
            (split_dir / name).write_text(text)
        print(f"{split}: {len(teams)} teams")


if __name__ == "__main__":
    main()
