from dataclasses import dataclass

import numpy as np
import torch
import torch.nn as nn
import torch.nn.functional as F


@dataclass
class DQNConfig:
    total_steps: int = 200_000
    lr: float = 1e-4
    gamma: float = 0.99
    batch_size: int = 64
    buffer_size: int = 100_000
    learning_starts: int = 5_000
    train_every: int = 4  # env steps per gradient step
    target_update_every: int = 2_000  # env steps between target network syncs
    epsilon_start: float = 1.0
    epsilon_end: float = 0.05
    epsilon_decay_steps: int = 60_000
    hidden_sizes: tuple[int, ...] = (512, 256)
    max_grad_norm: float = 10.0
    double: bool = True  # False gives the vanilla DQN target, for the ablation
    dueling: bool = False


class QNetwork(nn.Module):
    """MLP from observation features to one Q-value per action, optionally with a dueling head."""

    def __init__(self, obs_size: int, n_actions: int, hidden_sizes: tuple[int, ...], dueling: bool):
        super().__init__()
        layers, in_size = [], obs_size
        for size in hidden_sizes:
            layers += [nn.Linear(in_size, size), nn.ReLU()]
            in_size = size
        self.trunk = nn.Sequential(*layers)
        self.dueling = dueling
        if dueling:
            self.value_head = nn.Linear(in_size, 1)
            self.advantage_head = nn.Linear(in_size, n_actions)
        else:
            self.q_head = nn.Linear(in_size, n_actions)

    def forward(self, obs: torch.Tensor) -> torch.Tensor:
        h = self.trunk(obs)
        if not self.dueling:
            return self.q_head(h)
        advantages = self.advantage_head(h)
        return self.value_head(h) + advantages - advantages.mean(dim=1, keepdim=True)


class ReplayBuffer:
    """Fixed-size circular buffer; stores the next state's action mask for the masked target."""

    def __init__(self, capacity: int, obs_size: int, n_actions: int):
        self.capacity = capacity
        self.obs = np.zeros((capacity, obs_size), dtype=np.float32)
        self.next_obs = np.zeros((capacity, obs_size), dtype=np.float32)
        self.next_mask = np.zeros((capacity, n_actions), dtype=bool)
        self.actions = np.zeros(capacity, dtype=np.int64)
        self.rewards = np.zeros(capacity, dtype=np.float32)
        self.dones = np.zeros(capacity, dtype=bool)
        self.index, self.size = 0, 0

    def add(self, obs, action, reward, next_obs, next_mask, done):
        i = self.index
        self.obs[i], self.actions[i], self.rewards[i] = obs, action, reward
        self.next_obs[i], self.next_mask[i], self.dones[i] = next_obs, next_mask, done
        self.index = (i + 1) % self.capacity
        self.size = min(self.size + 1, self.capacity)

    def sample(self, batch_size: int, rng: np.random.Generator) -> dict[str, torch.Tensor]:
        """Uniform random batch of stored transitions, with replacement, as tensors."""
        idx = rng.integers(0, self.size, size=batch_size)
        return {
            "obs": torch.from_numpy(self.obs[idx]),
            "actions": torch.from_numpy(self.actions[idx]),
            "rewards": torch.from_numpy(self.rewards[idx]),
            "next_obs": torch.from_numpy(self.next_obs[idx]),
            "next_mask": torch.from_numpy(self.next_mask[idx]),
            "dones": torch.from_numpy(self.dones[idx]),
        }


def masked(q_values: torch.Tensor, mask: torch.Tensor) -> torch.Tensor:
    """Set Q-values of illegal actions to -inf."""
    return q_values.masked_fill(~mask, float("-inf"))


class DQNAgent:
    """Online and target Q-networks with an epsilon-greedy masked policy."""

    def __init__(self, obs_size: int, n_actions: int, config: DQNConfig, seed: int = 0):
        torch.manual_seed(seed)
        self.config = config
        self.n_actions = n_actions
        self.rng = np.random.default_rng(seed)
        self.q_net = QNetwork(obs_size, n_actions, config.hidden_sizes, config.dueling)
        self.target_net = QNetwork(obs_size, n_actions, config.hidden_sizes, config.dueling)
        self.target_net.load_state_dict(self.q_net.state_dict())
        self.optimizer = torch.optim.Adam(self.q_net.parameters(), lr=config.lr)
        self.replay_buffer = ReplayBuffer(config.buffer_size, obs_size, n_actions)

    def epsilon(self, step: int) -> float:
        """Linear decay from epsilon_start to epsilon_end."""
        frac = min(step / self.config.epsilon_decay_steps, 1.0)
        return self.config.epsilon_start + frac * (self.config.epsilon_end - self.config.epsilon_start)

    def act(self, obs: dict, epsilon: float = 0.0) -> int:
        """Random legal action with probability epsilon, otherwise the legal action with the highest Q-value."""
        legal = np.flatnonzero(obs["action_mask"])
        if self.rng.random() < epsilon:
            return int(self.rng.choice(legal))
        with torch.no_grad():
            q = self.q_net(torch.from_numpy(obs["observation"]).unsqueeze(0))[0]
        mask = torch.from_numpy(obs["action_mask"].astype(bool))
        return int(masked(q, mask).argmax())

    def update(self) -> float:
        """One gradient step on a replay batch; returns the Huber loss."""
        batch = self.replay_buffer.sample(self.config.batch_size, self.rng)
        q = self.q_net(batch["obs"]).gather(1, batch["actions"].unsqueeze(1)).squeeze(1)

        # bootstrap target, masking illegal next actions before the max
        with torch.no_grad():
            next_target_q = self.target_net(batch["next_obs"])
            if self.config.double:
                # online net picks the action, target net scores it
                next_actions = masked(self.q_net(batch["next_obs"]), batch["next_mask"]).argmax(dim=1, keepdim=True)
                next_q = next_target_q.gather(1, next_actions).squeeze(1)
            else:
                next_q = masked(next_target_q, batch["next_mask"]).max(dim=1).values
            # terminal next states have no legal actions, so their -inf is replaced by 0
            next_q = torch.where(batch["dones"], torch.zeros_like(next_q), next_q)
            target = batch["rewards"] + self.config.gamma * next_q

        loss = F.smooth_l1_loss(q, target)
        self.optimizer.zero_grad()
        loss.backward()
        nn.utils.clip_grad_norm_(self.q_net.parameters(), self.config.max_grad_norm)
        self.optimizer.step()
        return loss.item()

    def sync_target(self):
        self.target_net.load_state_dict(self.q_net.state_dict())
