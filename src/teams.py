"""Load the fixed Gen 2 OU team pools and hand them to poke-env.

Generated by Claude Code.
"""

import random
from pathlib import Path

from poke_env.teambuilder import Teambuilder

TEAMS_DIR = Path(__file__).resolve().parent.parent / "data" / "teams"
SPLITS = ("train", "val", "test")
POOLS = {"ladder": "ladder_*.gen2ou_team", "expert": "team_*.gen2ou_team"}  # file name patterns


def load_teams(split: str, pool: str | None = None) -> list[str]:
    """Return a split's teams as packed Showdown team strings, optionally only its ladder or expert pool."""
    if split not in SPLITS:
        raise ValueError(f"unknown split {split!r}, expected one of {SPLITS}")
    if pool is not None and pool not in POOLS:
        raise ValueError(f"unknown pool {pool!r}, expected one of {list(POOLS)}")
    paths = sorted((TEAMS_DIR / split).glob(POOLS[pool] if pool else "*.gen2ou_team"))
    if not paths:
        raise FileNotFoundError(f"no team files in {TEAMS_DIR / split}")
    teams = []
    for path in paths:
        # trailing blank lines in the files parse as an empty seventh Pokemon
        mons = [mon for mon in Teambuilder.parse_showdown_team(path.read_text()) if mon.moves]
        if len(mons) != 6:
            raise ValueError(f"{path.name} has {len(mons)} Pokemon, expected 6")
        teams.append(Teambuilder.join_team(mons))
    return teams


class RandomTeamPool(Teambuilder):
    """Teambuilder that gives each battle a team drawn uniformly from a pool."""

    def __init__(self, teams: list[str], seed: int | None = None):
        self.teams = teams
        self.rng = random.Random(seed)

    def yield_team(self) -> str:
        return self.rng.choice(self.teams)
